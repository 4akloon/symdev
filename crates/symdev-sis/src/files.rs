use super::array::SisArray;
use super::field::SisEncode;
use super::string::SisString;
use super::words::SisWords;

pub struct SisWord41 {
    pub value: u32,
}

impl SisWord41 {
    pub const KIND: u32 = 41;

    pub fn new(value: u32) -> Self {
        Self { value }
    }

    pub fn payload(&self) -> [u8; 4] {
        self.value.to_le_bytes()
    }
}

impl SisEncode for SisWord41 {
    const KIND: u32 = SisWord41::KIND;

    fn payload(&self) -> Vec<u8> {
        SisWord41::payload(self).to_vec()
    }
}

pub struct SisHash {
    pub words: [u32; 3],
    pub digest: Vec<u8>,
}

impl SisHash {
    pub const KIND: u32 = 25;

    pub fn new(words: [u32; 3], digest: impl Into<Vec<u8>>) -> Self {
        Self {
            words,
            digest: digest.into(),
        }
    }

    pub fn payload(&self) -> Vec<u8> {
        let mut out: Vec<u8> = self.words.iter().flat_map(|v| v.to_le_bytes()).collect();
        out.extend_from_slice(&self.digest);
        out
    }
}

impl SisEncode for SisHash {
    const KIND: u32 = SisHash::KIND;

    fn payload(&self) -> Vec<u8> {
        SisHash::payload(self)
    }
}

pub struct SisFile {
    pub dest: SisString,
    pub empty: SisString,
    pub word41: Option<SisWord41>,
    pub hash: SisHash,
    pub empty2: SisString,
    pub tail: [u32; 5],
}

impl SisFile {
    pub const KIND: u32 = 24;

    pub fn new(
        dest: SisString,
        empty: SisString,
        word41: Option<SisWord41>,
        hash: SisHash,
        empty2: SisString,
        tail: [u32; 5],
    ) -> Self {
        Self {
            dest,
            empty,
            word41,
            hash,
            empty2,
            tail,
        }
    }

    pub fn payload(&self) -> Vec<u8> {
        // makesis writes type 41 only for files that carry capabilities (experiment 43).
        let word41 = self.word41.as_ref().map(|w| w.field().bytes());
        let mut out = [
            self.dest.field().bytes(),
            self.empty.field().bytes(),
            word41.unwrap_or_default(),
            self.hash.field().bytes(),
            self.empty2.field().bytes(),
        ]
        .concat();
        out.extend(self.tail.iter().flat_map(|v| v.to_le_bytes()));
        out
    }
}

impl SisEncode for SisFile {
    const KIND: u32 = SisFile::KIND;

    fn payload(&self) -> Vec<u8> {
        SisFile::payload(self)
    }
}

pub struct SisFiles {
    pub files: SisArray,
    pub word_d: SisWords,
    pub word_1a: SisWords,
}

impl SisFiles {
    pub const KIND: u32 = 28;

    pub fn new(files: SisArray, word_d: SisWords, word_1a: SisWords) -> Self {
        Self {
            files,
            word_d,
            word_1a,
        }
    }

    pub fn payload(&self) -> Vec<u8> {
        let mut out = self.files.field().bytes();
        out.extend(self.word_d.field().bytes());
        out.extend(self.word_1a.field().bytes());
        out
    }
}

impl SisEncode for SisFiles {
    const KIND: u32 = SisFiles::KIND;

    fn payload(&self) -> Vec<u8> {
        SisFiles::payload(self)
    }
}

