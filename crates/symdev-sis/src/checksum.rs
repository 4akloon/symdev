use super::field::{SisEncode, SisField};
use symdev_uidcrc::epoc_crc16;

pub struct SisChecksum34 {
    pub value: [u8; 2],
}

impl SisChecksum34 {
    pub const KIND: u32 = 34;

    pub fn new(value: [u8; 2]) -> Self {
        Self { value }
    }

    pub fn of(inner: &SisField) -> Self {
        Self::new(epoc_crc16(&inner.bytes()).to_le_bytes())
    }

    pub fn payload(&self) -> [u8; 2] {
        self.value
    }
}

impl SisEncode for SisChecksum34 {
    const KIND: u32 = Self::KIND;

    fn payload(&self) -> Vec<u8> {
        SisChecksum34::payload(self).to_vec()
    }
}

