use super::field::SisField;
use super::files::SisFiles;
use super::info::SisInfo;
use super::language::SisLanguages;
use super::products::SisProducts;
use super::words::{SisU32, SisWords16, SisWords19};

pub struct SisController {
    pub info: SisInfo,
    pub words16: SisWords16,
    pub languages: SisLanguages,
    pub products: SisProducts,
    pub words19: SisWords19,
    pub files: SisFiles,
    pub trailer: SisU32,
}

impl SisController {
    pub const KIND: u32 = 13;

    pub fn new(
        info: SisInfo,
        words16: SisWords16,
        languages: SisLanguages,
        products: SisProducts,
        words19: SisWords19,
        files: SisFiles,
        trailer: SisU32,
    ) -> Self {
        Self {
            info,
            words16,
            languages,
            products,
            words19,
            files,
            trailer,
        }
    }

    pub fn payload(&self) -> Vec<u8> {
        [
            self.info.field().bytes(),
            self.words16.field().bytes(),
            self.languages.field().bytes(),
            self.products.field().bytes(),
            self.words19.field().bytes(),
            self.files.field().bytes(),
            self.trailer.field().bytes(),
        ]
        .concat()
    }

    pub fn field(&self) -> SisField {
        SisField::new(Self::KIND, self.payload())
    }
}

